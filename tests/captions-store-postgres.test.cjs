async function database({ supabaseExtensions = false } = {}) {
  const db = new PGlite({ extensions: { pgcrypto } });
  // Supabase installs pgcrypto in its own `extensions` schema; by default it lands in public here.
  if (supabaseExtensions) await db.exec(`CREATE SCHEMA extensions; CREATE EXTENSION pgcrypto SCHEMA extensions;`);
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE SCHEMA auth;
    CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    CREATE OR REPLACE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.role', true), '')
    $$;
    CREATE OR REPLACE FUNCTION auth.email() RETURNS text LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.email', true), '')
    $$;
    GRANT USAGE ON SCHEMA auth TO authenticated, service_role;
    GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA auth TO authenticated, service_role;
    CREATE OR REPLACE FUNCTION is_admin() RETURNS boolean LANGUAGE sql STABLE AS $$
      SELECT coalesce(auth.email(),'') IN ('christychowtc@gmail.com','mitchell.tsui.mc@gmail.com')
    $$;
    CREATE SCHEMA realtime;
    CREATE TABLE realtime.messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, topic text, extension text);
    ALTER TABLE realtime.messages ENABLE ROW LEVEL SECURITY;
    GRANT USAGE ON SCHEMA realtime TO authenticated, service_role;
    GRANT SELECT, INSERT ON realtime.messages TO authenticated;
    CREATE OR REPLACE FUNCTION realtime.topic() RETURNS text LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('realtime.topic', true), '')
    $$;
  `);
  await db.exec(await fs.readFile(migrationPath, 'utf8'));
  await db.exec(await fs.readFile(guestLinksPath, 'utf8'));
  return db;
}

async function asService(db) {
  await db.exec(`SELECT set_config('request.jwt.claim.role','service_role',false);`);
}

function storeResponse(status, payload) {
  return { ok: status >= 200 && status < 300, status,
    text: async () => payload === undefined ? '' : JSON.stringify(payload) };
}

function makeStoreFetch(db) {
  const jsonArguments = new Set(['p_source_segment','p_segment','p_captions','p_payloads','p_details_safe']);
  const setFunctions = new Set(['caption_claim_outbox','caption_claim_approved_reviews']);
  return async (url, options = {}) => {
    const match = /^\/rest\/v1\/rpc\/([a-z_]+)$/.exec(new URL(url).pathname);
    if (!match) return storeResponse(404, { code: 'not_found' });
    const name = match[1];
    assert.match(name, /^caption_[a-z_]+$/);
    try {
      await asService(db);
      const args = options.body ? JSON.parse(options.body) : {};
      const values = [];
      const named = Object.entries(args).map(([key, value], index) => {
        values.push(jsonArguments.has(key) ? JSON.stringify(value) : value);
        return `${key} => $${index + 1}${jsonArguments.has(key) ? '::jsonb' : ''}`;
      });
      const returnsSet = setFunctions.has(name);
      const sql = returnsSet ? `SELECT * FROM ${name}(${named.join(',')})`
        : `SELECT ${name}(${named.join(',')}) AS value`;
      const result = await db.query(sql, values);
      return storeResponse(200, returnsSet ? result.rows : result.rows[0]?.value);
    } catch (error) {
      return storeResponse(error.code === '42501' ? 403 : 400, { code: error.code || 'db_error' });
    }
  };
}

