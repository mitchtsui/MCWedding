  await refused(event.event_id, invite.token);
  await db.query(`UPDATE caption_invites SET active=true, created_at=now()-interval '2 days', expires_at=now()-interval '1 second' WHERE id=$1`, [invite.invite_id]);
  await refused(event.event_id, invite.token);
