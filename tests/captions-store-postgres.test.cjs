  const recovered = { language:'en',text:'Recovered translation',status:'final',captionRevision:1,sourceRevision:1,origin:'ai_live' };
  const saved = (await db.query(`SELECT caption_persist_final_and_enqueue($1,1,3,$2::jsonb,$3::jsonb,$4::jsonb,'recovered') AS value`,
    [run.run_id,JSON.stringify(source),JSON.stringify([recovered]),JSON.stringify(payload(recovered))])).rows[0].value;
